create table if not exists public.warehouse_state (
  id integer primary key check (id = 1),
  state jsonb not null,
  revision bigint not null default 1,
  updated_at timestamptz not null default now()
);

insert into public.warehouse_state(id,state,revision)
values (1, '{"zones":[{"id":"A","name":"A","rows":1,"cols":9,"topLabels":true},{"id":"B","name":"B","rows":2,"cols":9,"topLabels":true},{"id":"C","name":"C","rows":2,"cols":9,"topLabels":true},{"id":"D","name":"D","rows":2,"cols":9,"topLabels":true},{"id":"E","name":"E","rows":2,"cols":9,"topLabels":true},{"id":"F","name":"F","rows":2,"cols":9,"topLabels":true}],"assignments":{},"colors":{}}'::jsonb, 1)
on conflict (id) do nothing;

create table if not exists public.markets (
  id bigint generated by default as identity primary key,
  name text not null,
  code text not null default '',
  address text not null default ''
);
create index if not exists idx_markets_code on public.markets(code);
create index if not exists idx_markets_name on public.markets(name);

alter table public.warehouse_state enable row level security;
alter table public.markets enable row level security;

drop policy if exists "warehouse_state_public_read" on public.warehouse_state;
create policy "warehouse_state_public_read" on public.warehouse_state for select to anon, authenticated using (true);

drop policy if exists "markets_public_read" on public.markets;
create policy "markets_public_read" on public.markets for select to anon, authenticated using (true);

create or replace function public.save_warehouse_state(p_state jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare new_revision bigint;
begin
  if jsonb_typeof(p_state) <> 'object'
     or jsonb_typeof(p_state->'zones') <> 'array'
     or jsonb_typeof(p_state->'assignments') <> 'object' then
    raise exception 'Invalid warehouse state';
  end if;
  update public.warehouse_state
     set state=p_state, revision=revision+1, updated_at=now()
   where id=1
   returning revision into new_revision;
  return new_revision;
end;
$$;
revoke all on function public.save_warehouse_state(jsonb) from public;
grant execute on function public.save_warehouse_state(jsonb) to anon, authenticated;

